const GQL_ENDPOINT = process.env.NEXT_PUBLIC_HASHNODE_GQL_ENDPOINT;

type Props = {
	publication: PublicationFragment;
	initialPosts: PostFragment[];
	topicClusters: TopicCluster[];
};

type QueryUpdates = Partial<Record<'view' | 'sort' | 'tag' | 'series', string | null>>;
type SortField = 'created' | 'updated' | 'popular';

const SORT_ROW_OPTIONS: Array<{
	field: SortField;
	label: string;
	desc: PostListSort;
	asc: PostListSort;
}> = [
	{ field: 'created', label: 'Created on', desc: 'created-desc', asc: 'created-asc' },
	{ field: 'updated', label: 'Updated on', desc: 'updated-desc', asc: 'updated-asc' },
	{ field: 'popular', label: 'Popularity', desc: 'popular-desc', asc: 'popular-asc' },
];

const formatViews = (views: number) => {
	if (views >= 1_000_000) {
		return `${(views / 1_000_000).toFixed(1)}M`;
	}

	if (views >= 1_000) {
		return `${(views / 1_000).toFixed(1)}K`;
	}

	return `${views}`;
};

const getQueryValue = (value: string | string[] | undefined) =>
	typeof value === 'string' && value.length > 0 ? value : '';

const buildTagOptions = (posts: PostFragment[]) => {
	const tags = new Map<string, { slug: string; name: string; count: number }>();

	posts.forEach((post) => {
		post.tags?.forEach((tag) => {
			const existing = tags.get(tag.slug);
			tags.set(tag.slug, {
				slug: tag.slug,
				name: formatTagName(tag.name),
				count: (existing?.count ?? 0) + 1,
			});
		});
	});

	return [...tags.values()].sort((a, b) => b.count - a.count || a.name.localeCompare(b.name));
};

const buildSeriesOptions = (posts: PostFragment[]) => {
	const series = new Map<string, { slug: string; name: string; count: number }>();

	posts.forEach((post) => {
		if (!post.series) {
			return;
		}

		const existing = series.get(post.series.slug);
		series.set(post.series.slug, {
			slug: post.series.slug,
			name: post.series.name,
			count: (existing?.count ?? 0) + 1,
		});
	});

	return [...series.values()].sort((a, b) => b.count - a.count || a.name.localeCompare(b.name));
};

const getSortField = (sort: PostListSort): SortField => {
	if (sort.startsWith('created')) {
		return 'created';
	}

	if (sort.startsWith('updated')) {
		return 'updated';
	}

	return 'popular';
};

const isAscendingSort = (sort: PostListSort) => sort.endsWith('asc');

const getNextSort = (currentSort: PostListSort, field: SortField): PostListSort => {
	const option = SORT_ROW_OPTIONS.find((item) => item.field === field);
	if (!option) {
		return currentSort;
	}

	if (getSortField(currentSort) === field) {
		return isAscendingSort(currentSort) ? option.desc : option.asc;
	}

	return option.desc;
};

const getVisibleOptions = <T extends { slug: string }>(
	options: T[],
	selectedSlug: string,
	limit: number,
) => {
	const topOptions = options.slice(0, limit);
	if (!selectedSlug || topOptions.some((option) => option.slug === selectedSlug)) {
		return topOptions;
	}

	const selected = options.find((option) => option.slug === selectedSlug);
	return selected ? [selected, ...topOptions.slice(0, Math.max(limit - 1, 0))] : topOptions;
};

export default function AllPostsPage({ publication, initialPosts, topicClusters }: Props) {
	const router = useRouter();
	const [searchTerm, setSearchTerm] = useState('');

	const view = parsePostListView(router.query.view);
	const sort = parsePostListSort(router.query.sort, view);
	const tagSlug = getQueryValue(router.query.tag);
	const seriesSlug = getQueryValue(router.query.series);

	const updateQuery = (updates: QueryUpdates) => {
		const nextState = {
			view,
			sort,
			tag: tagSlug,
			series: seriesSlug,
			...updates,
		};

		const nextQuery = Object.fromEntries(
			Object.entries(nextState).filter(([, value]) => value && value.length > 0),
		);

		router.replace(
			{
				pathname: '/posts',
				query: nextQuery,
			},
			undefined,
			{ shallow: true, scroll: false },
		);
	};

	const clearFilters = () => {
		setSearchTerm('');
		router.replace('/posts', undefined, { shallow: true, scroll: false });
	};

	const tagOptions = useMemo(() => buildTagOptions(initialPosts), [initialPosts]);
	const seriesOptions = useMemo(() => buildSeriesOptions(initialPosts), [initialPosts]);
	const visibleTagOptions = useMemo(
		() => getVisibleOptions(tagOptions, tagSlug, 6),
		[tagOptions, tagSlug],
	);
	const visibleSeriesOptions = useMemo(
		() => getVisibleOptions(seriesOptions, seriesSlug, 5),
		[seriesOptions, seriesSlug],
	);

	const viewCounts = useMemo(
		() => ({
			all: getPostsForView(initialPosts, 'all').length,
			created: getPostsForView(initialPosts, 'created').length,
			updated: getPostsForView(initialPosts, 'updated').length,
			top: getPostsForView(initialPosts, 'top').length,
		}),
		[initialPosts],
	);

	const filteredPosts = useMemo(() => {
		const basePosts = getPostsForView(initialPosts, view);
		const matchingPosts = filterPosts(basePosts, {
			searchTerm,
			tagSlug: tagSlug || null,
			seriesSlug: seriesSlug || null,
			createdFrom: '',
			createdTo: '',
			updatedFrom: '',
			updatedTo: '',
		});

		return sortPosts(matchingPosts, sort);
	}, [initialPosts, searchTerm, seriesSlug, sort, tagSlug, view]);

	const activeFilterCount = [searchTerm, tagSlug, seriesSlug].filter(Boolean).length;
	const activeView = POST_VIEW_META[view];
	const activeSortField = getSortField(sort);

	return (
		<AppProvider publication={publication} footerPosts={initialPosts}>
			<Layout>
				<Head>
					<title>All Posts - {publication.title}</title>
					<meta name="description" content={`Browse all posts from ${publication.title}`} />
					<meta property="og:title" content={`All Posts - ${publication.title}`} />
					<meta property="og:description" content={`Browse all posts from ${publication.title}`} />
					<meta property="og:image" content={publication.ogMetaData.image || getAutogeneratedPublicationOG(publication)} />
					<meta property="twitter:card" content="summary_large_image" />
					<meta property="twitter:title" content={`All Posts - ${publication.title}`} />
					<meta property="twitter:description" content={`Browse all posts from ${publication.title}`} />
					<meta property="twitter:image" content={publication.ogMetaData.image || getAutogeneratedPublicationOG(publication)} />
					<script
						type="application/ld+json"
						dangerouslySetInnerHTML={{ __html: JSON.stringify(addPublicationJsonLd(publication)) }}
					/>
				</Head>
				<Container className="mx-auto w-full">
					<PersonalHeader />
					<div className="max-w-6xl mx-auto w-full px-4 sm:px-5 py-12 flex flex-col gap-8">
						<div className="flex flex-col gap-4 md:flex-row md:items-end md:justify-between">
							<div>
								<p className="text-sm font-semibold uppercase tracking-wide text-neutral-500 dark:text-neutral-400 mb-2">
									Post explorer
								</p>
								<h1 className="text-4xl md:text-5xl font-bold text-neutral-900 dark:text-neutral-50 mb-3">
									{activeView.label}
								</h1>
								<p className="text-lg text-neutral-600 dark:text-neutral-300 max-w-3xl">
									{activeView.description}
								</p>
							</div>
							<div className="text-sm text-neutral-500 dark:text-neutral-400">
								{filteredPosts.length} result{filteredPosts.length !== 1 ? 's' : ''}
								{activeFilterCount > 0 ? ` · ${activeFilterCount} active filter${activeFilterCount !== 1 ? 's' : ''}` : ''}
							</div>
						</div>

					{topicClusters.length > 0 && <TopicClusters clusters={topicClusters} />}
						<div className="rounded-2xl border border-neutral-200 dark:border-neutral-800 bg-white dark:bg-neutral-900 p-5 flex flex-col gap-5">
							<div className="flex flex-col gap-4 lg:flex-row lg:items-center lg:justify-between">
								<div className="flex flex-wrap items-center gap-2">
									<span className="text-sm font-semibold text-neutral-700 dark:text-neutral-300 mr-1">
										View
									</span>
									{(['all', 'created', 'updated', 'top'] as PostListView[]).map((preset) => (
										<button
											key={preset}
											onClick={() =>
												updateQuery({
													view: preset === 'all' ? null : preset,
													sort: DEFAULT_SORT_BY_VIEW[preset],
												})
											}
											className={`rounded-full px-3 py-1.5 text-sm font-medium transition-colors ${
												view === preset
													? 'bg-blue-600 text-white'
													: 'bg-neutral-100 text-neutral-700 hover:bg-neutral-200 dark:bg-neutral-800 dark:text-neutral-200 dark:hover:bg-neutral-700'
											}`}
										>
											{POST_VIEW_META[preset].label} <span className="opacity-70">({viewCounts[preset]})</span>
										</button>
									))}
								</div>
								<div className="w-full lg:max-w-sm">
									<input
										type="text"
										value={searchTerm}
										onChange={(e) => setSearchTerm(e.target.value)}
										placeholder="Search posts..."
										className="w-full rounded-full border border-neutral-200 dark:border-neutral-700 bg-white dark:bg-neutral-950 px-4 py-2.5 text-neutral-900 dark:text-neutral-50 placeholder-neutral-400 focus:outline-none focus:ring-2 focus:ring-blue-500"
									/>
								</div>
							</div>

							<div className="flex flex-wrap items-center gap-3">
								<span className="text-sm font-semibold text-neutral-700 dark:text-neutral-300">
									Sort by
								</span>
								{SORT_ROW_OPTIONS.map((option) => {
									const isActive = activeSortField === option.field;
									const direction = isActive && isAscendingSort(sort) ? '↑' : '↓';

									return (
										<button
											key={option.field}
											onClick={() => updateQuery({ sort: getNextSort(sort, option.field) })}
											className={`inline-flex items-center gap-2 rounded-full px-3 py-1.5 text-sm font-medium transition-colors ${
												isActive
													? 'bg-neutral-900 text-white dark:bg-neutral-100 dark:text-neutral-900'
													: 'bg-neutral-100 text-neutral-700 hover:bg-neutral-200 dark:bg-neutral-800 dark:text-neutral-200 dark:hover:bg-neutral-700'
											}`}
										>
											{option.label}
											<span className={`text-base leading-none ${isActive ? 'opacity-100' : 'opacity-40'}`}>
												{direction}
											</span>
										</button>
									);
								})}
							</div>

							<div className="flex flex-col gap-3">
								<div className="flex flex-wrap items-center gap-2">
									<span className="text-sm font-semibold text-neutral-700 dark:text-neutral-300 mr-1">
										Tags
									</span>
									<button
										onClick={() => updateQuery({ tag: null })}
										className={`rounded-full px-3 py-1.5 text-sm font-medium transition-colors ${
											!tagSlug
												? 'bg-blue-600 text-white'
												: 'bg-neutral-100 text-neutral-700 hover:bg-neutral-200 dark:bg-neutral-800 dark:text-neutral-200 dark:hover:bg-neutral-700'
										}`}
									>
										All
									</button>
									{visibleTagOptions.map((tag) => (
										<button
											key={tag.slug}
											onClick={() => updateQuery({ tag: tag.slug })}
											className={`rounded-full px-3 py-1.5 text-sm font-medium transition-colors ${
												tagSlug === tag.slug
													? 'bg-blue-600 text-white'
													: 'bg-neutral-100 text-neutral-700 hover:bg-neutral-200 dark:bg-neutral-800 dark:text-neutral-200 dark:hover:bg-neutral-700'
											}`}
										>
											{tag.name}
										</button>
									))}
								</div>

								{seriesOptions.length > 0 && (
									<div className="flex flex-wrap items-center gap-2">
										<span className="text-sm font-semibold text-neutral-700 dark:text-neutral-300 mr-1">
											Series
										</span>
										<button
											onClick={() => updateQuery({ series: null })}
											className={`rounded-full px-3 py-1.5 text-sm font-medium transition-colors ${
												!seriesSlug
													? 'bg-purple-600 text-white'
													: 'bg-neutral-100 text-neutral-700 hover:bg-neutral-200 dark:bg-neutral-800 dark:text-neutral-200 dark:hover:bg-neutral-700'
											}`}
										>
											All
										</button>
										{visibleSeriesOptions.map((series) => (
											<button
												key={series.slug}
												onClick={() => updateQuery({ series: series.slug })}
												className={`rounded-full px-3 py-1.5 text-sm font-medium transition-colors ${
													seriesSlug === series.slug
														? 'bg-purple-600 text-white'
														: 'bg-neutral-100 text-neutral-700 hover:bg-neutral-200 dark:bg-neutral-800 dark:text-neutral-200 dark:hover:bg-neutral-700'
												}`}
											>
												{series.name}
											</button>
										))}
									</div>
								)}
							</div>

							{activeFilterCount > 0 && (
								<div className="flex flex-wrap items-center gap-2 border-t border-neutral-200 pt-4 dark:border-neutral-800">
									<span className="text-sm font-semibold text-neutral-700 dark:text-neutral-300">
										Active
									</span>
									{searchTerm ? (
										<span className="rounded-full bg-neutral-100 px-3 py-1 text-sm text-neutral-700 dark:bg-neutral-800 dark:text-neutral-200">
											Search: {searchTerm}
										</span>
									) : null}
									{tagSlug ? (
										<span className="rounded-full bg-blue-100 px-3 py-1 text-sm text-blue-700 dark:bg-blue-900/40 dark:text-blue-200">
											Tag: {tagOptions.find((tag) => tag.slug === tagSlug)?.name ?? tagSlug}
										</span>
									) : null}
									{seriesSlug ? (
										<span className="rounded-full bg-purple-100 px-3 py-1 text-sm text-purple-700 dark:bg-purple-900/40 dark:text-purple-200">
											Series: {seriesOptions.find((series) => series.slug === seriesSlug)?.name ?? seriesSlug}
										</span>
									) : null}
									<button
										onClick={clearFilters}
										className="ml-1 text-sm font-semibold text-blue-600 hover:text-blue-700 dark:text-blue-400 dark:hover:text-blue-300"
									>
										Clear all
									</button>
								</div>
							)}
						</div>

						{filteredPosts.length > 0 ? (
							<div className="grid grid-cols-1 md:grid-cols-2 xl:grid-cols-3 gap-6">
								{filteredPosts.map((post) => (
									<article
										key={post.id}
										className="flex h-full flex-col overflow-hidden rounded-2xl border border-neutral-200 dark:border-neutral-800 bg-white dark:bg-neutral-900"
									>
										{post.coverImage?.url ? (
											<Link href={`/${post.slug}`} className="block overflow-hidden">
												<img
													src={post.coverImage.url}
													alt={post.title}
													className="h-52 w-full object-cover transition-transform duration-300 hover:scale-105"
												/>
											</Link>
										) : null}
										<div className="flex flex-1 flex-col p-5">
											<div className="mb-3 flex flex-wrap gap-2">
												{post.series ? (
													<button
														onClick={() => updateQuery({ series: post.series?.slug || null })}
														className="rounded-full bg-purple-100 px-3 py-1 text-xs font-semibold text-purple-700 transition-colors hover:bg-purple-200 dark:bg-purple-900/40 dark:text-purple-200"
													>
														Series: {post.series.name}
													</button>
												) : null}
												{post.tags?.slice(0, 2).map((tag) => (
													<button
														key={tag.id}
														onClick={() => updateQuery({ tag: tag.slug })}
														className="rounded-full bg-blue-100 px-3 py-1 text-xs font-semibold text-blue-700 transition-colors hover:bg-blue-200 dark:bg-blue-900/40 dark:text-blue-200"
													>
														{formatTagName(tag.name)}
													</button>
												))}
											</div>
											<Link href={`/${post.slug}`} className="group">
												<h2 className="text-xl font-bold text-neutral-900 transition-colors group-hover:text-blue-600 dark:text-neutral-50 dark:group-hover:text-blue-400">
													{post.title}
												</h2>
											</Link>
											<p className="mt-3 line-clamp-3 text-sm leading-6 text-neutral-600 dark:text-neutral-400">
												{post.brief}
											</p>
											<div className="mt-5 grid grid-cols-2 gap-3 text-sm text-neutral-500 dark:text-neutral-400">
												<div>
													<p className="text-xs uppercase tracking-wide text-neutral-400 dark:text-neutral-500">
														Created
													</p>
													<DateFormatter dateString={post.publishedAt} />
												</div>
												<div>
													<p className="text-xs uppercase tracking-wide text-neutral-400 dark:text-neutral-500">
														Updated
													</p>
													<DateFormatter dateString={getEffectiveUpdatedAt(post)} />
												</div>
												<div>
													<p className="text-xs uppercase tracking-wide text-neutral-400 dark:text-neutral-500">
														Popularity
													</p>
													<p>{formatViews(post.views)} views</p>
												</div>
												<div>
													<p className="text-xs uppercase tracking-wide text-neutral-400 dark:text-neutral-500">
														Read time
													</p>
													<p>{post.readTimeInMinutes} min read</p>
												</div>
											</div>
											<div className="mt-5 flex items-center justify-between border-t border-neutral-200 pt-4 text-sm text-neutral-500 dark:border-neutral-800 dark:text-neutral-400">
												<span>{post.comments.totalDocuments} comment{post.comments.totalDocuments !== 1 ? 's' : ''}</span>
												<Link
													href={`/${post.slug}`}
													className="font-semibold text-blue-600 hover:text-blue-700 dark:text-blue-400 dark:hover:text-blue-300"
												>
													Read post
												</Link>
											</div>
										</div>
									</article>
								))}
							</div>
						) : (
							<div className="rounded-2xl border border-dashed border-neutral-300 dark:border-neutral-700 px-6 py-16 text-center">
								<h2 className="text-2xl font-semibold text-neutral-900 dark:text-neutral-50">
									No posts match the current filters
								</h2>
								<p className="mt-3 text-neutral-600 dark:text-neutral-400">
									Try clearing filters or switching the active view.
								</p>
							</div>
						)}
					</div>
					<Footer />
				</Container>
			</Layout>
		</AppProvider>
	);
}

export const getStaticProps: GetStaticProps<Props> = async () => {
	const data = await request<PostsByPublicationQuery, PostsByPublicationQueryVariables>(
		GQL_ENDPOINT,
		PostsByPublicationDocument,
		{
			first: 20,
			host: process.env.NEXT_PUBLIC_HASHNODE_PUBLICATION_HOST,
		},
	);

	const publication = data.publication;
	if (!publication) {
		return {
			notFound: true,
		};
	}

	const allPosts = (publication.posts.edges ?? []).map((edge) => edge.node);
	let cursor = publication.posts.pageInfo.endCursor;
	let hasNextPage = !!publication.posts.pageInfo.hasNextPage;

	while (hasNextPage && cursor) {
		const next = await request<MorePostsByPublicationQuery, MorePostsByPublicationQueryVariables>(
			GQL_ENDPOINT,
			MorePostsByPublicationDocument,
			{ first: 20, host: process.env.NEXT_PUBLIC_HASHNODE_PUBLICATION_HOST, after: cursor },
		);

		if (!next.publication) {
			break;
		}

		allPosts.push(...next.publication.posts.edges.map((edge) => edge.node));
		cursor = next.publication.posts.pageInfo.endCursor;
		hasNextPage = !!next.publication.posts.pageInfo.hasNextPage;
	}

	const topicClusters: TopicCluster[] = buildTopicClusters(allPosts);

	return {
		props: {
			publication,
			initialPosts: allPosts,
			topicClusters,
		},
		revalidate: 1,
	};
};
