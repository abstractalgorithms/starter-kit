import { getAutogeneratedPublicationOG } from '@starter-kit/utils/social/og';
import request from 'graphql-request';
import type { GetStaticProps } from 'next';
import Head from 'next/head';
import Link from 'next/link';
import { useRouter } from 'next/router';
import { useEffect, useMemo, useState } from 'react';
import { Container } from '../components/container';
import { AppProvider } from '../components/contexts/appContext';
import { Footer } from '../components/footer';
import { Layout } from '../components/layout';
import { PersonalHeader } from '../components/personal-theme-header';
import { getFooterPosts } from '../lib/api/footerData';
import {
	PostFragment,
	PublicationByHostDocument,
	PublicationByHostQuery,
	PublicationByHostQueryVariables,
	PublicationFragment,
} from '../generated/graphql';

const GQL_ENDPOINT = process.env.NEXT_PUBLIC_HASHNODE_GQL_ENDPOINT;
const REDIRECT_SECONDS = 8;

type Props = {
	publication: PublicationFragment | null;
	footerPosts: PostFragment[];
};

const getRedirectTarget = (path: string) => {
	const cleanPath = path.split('?')[0].replace(/\/$/, '').toLowerCase();

	if (cleanPath.startsWith('/tag/')) {
		return {
			href: cleanPath.replace(/^\/tag\//, '/topic/'),
			label: 'matching topic',
			title: 'That tag page moved to Topics.',
		};
	}

	if (cleanPath.startsWith('/topic/') || cleanPath.includes('topic')) {
		return { href: '/learn', label: 'Learn', title: 'That topic could not be found.' };
	}

	if (cleanPath.startsWith('/series/') || cleanPath.includes('series')) {
		return { href: '/series', label: 'Series', title: 'That series could not be found.' };
	}

	if (cleanPath.startsWith('/posts') || cleanPath.includes('blog') || cleanPath.includes('article')) {
		return { href: '/posts', label: 'Blog', title: 'That article could not be found.' };
	}

	if (cleanPath.includes('discover') || cleanPath.includes('guided') || cleanPath.includes('roadmap')) {
		return { href: '/learn', label: 'Learn', title: 'That learning page moved.' };
	}

	return { href: '/', label: 'Home', title: 'We could not find that page.' };
};

const MissingPageContent = ({ siteTitle }: { siteTitle: string }) => {
	const router = useRouter();
	const [countdown, setCountdown] = useState(REDIRECT_SECONDS);
	const target = useMemo(() => getRedirectTarget(router.asPath || ''), [router.asPath]);

	useEffect(() => {
		const tick = window.setInterval(() => {
			setCountdown((value) => Math.max(0, value - 1));
		}, 1000);
		const redirect = window.setTimeout(() => {
			void router.replace(target.href);
		}, REDIRECT_SECONDS * 1000);

		return () => {
			window.clearInterval(tick);
			window.clearTimeout(redirect);
		};
	}, [router, target.href]);

	const suggestions = [
		{ href: '/learn', label: 'Learn' },
		{ href: '/series', label: 'Series' },
		{ href: '/posts', label: 'Blog' },
		{ href: '/', label: 'Home' },
	];

	return (
		<>
			<Head>
				<title>{`Page Not Found - ${siteTitle}`}</title>
				<meta name="robots" content="noindex" />
				<meta name="description" content={`The requested page was not found on ${siteTitle}.`} />
			</Head>
			<main className="mx-auto flex min-h-[68vh] w-full max-w-[1440px] items-center px-5 py-16 md:px-8">
				<section className="grid w-full gap-8 rounded-xl border border-slate-200 bg-white p-6 shadow-sm md:grid-cols-[minmax(0,1fr)_320px] md:p-8">
					<div>
						<p className="text-sm font-black uppercase tracking-wide text-blue-600">404</p>
						<h1 className="mt-3 text-4xl font-black tracking-tight text-slate-950 md:text-5xl">
							{target.title}
						</h1>
						<p className="mt-4 max-w-2xl text-base leading-7 text-slate-600">
							The URL may be old, renamed, or no longer published. We will take you to {target.label} in {countdown} second{countdown === 1 ? '' : 's'}.
						</p>
						<div className="mt-7 flex flex-wrap gap-3">
							<Link href={target.href} className="inline-flex h-11 items-center rounded-lg bg-blue-600 px-5 text-sm font-black text-white shadow-lg shadow-blue-200 hover:bg-blue-700">
								Go to {target.label}
							</Link>
							<Link href="/" className="inline-flex h-11 items-center rounded-lg border border-slate-300 bg-white px-5 text-sm font-black text-slate-950 hover:border-blue-300 hover:text-blue-700">
								Back Home
							</Link>
						</div>
					</div>

					<aside className="rounded-lg border border-slate-200 bg-slate-50 p-5">
						<h2 className="text-base font-black text-slate-950">Try these instead</h2>
						<div className="mt-4 grid gap-2">
							{suggestions.map((item) => (
								<Link key={item.href} href={item.href} className="flex items-center justify-between rounded-lg bg-white px-4 py-3 text-sm font-bold text-slate-700 shadow-sm hover:text-blue-700">
									{item.label}
									<span aria-hidden="true">-&gt;</span>
								</Link>
							))}
						</div>
					</aside>
				</section>
			</main>
		</>
	);
};

export default function NotFoundPage({ publication, footerPosts }: Props) {
	if (!publication) {
		return (
			<Layout>
				<MissingPageContent siteTitle="Abstract Algorithms" />
			</Layout>
		);
	}

	return (
		<AppProvider publication={publication} footerPosts={footerPosts}>
			<Layout>
				<Container className="mx-auto w-full">
					<Head>
						<meta property="og:image" content={publication.ogMetaData?.image || getAutogeneratedPublicationOG(publication)} />
					</Head>
					<PersonalHeader />
					<MissingPageContent siteTitle={publication.title} />
					<Footer />
				</Container>
			</Layout>
		</AppProvider>
	);
}

export const getStaticProps: GetStaticProps<Props> = async () => {
	try {
		const data = await request<PublicationByHostQuery, PublicationByHostQueryVariables>(
			GQL_ENDPOINT,
			PublicationByHostDocument,
			{
				host: process.env.NEXT_PUBLIC_HASHNODE_PUBLICATION_HOST,
			},
		);

		if (!data.publication) {
			return { props: { publication: null, footerPosts: [] }, revalidate: 60 };
		}

		const footerPosts = await getFooterPosts();

		return {
			props: {
				publication: data.publication,
				footerPosts,
			},
			revalidate: 60,
		};
	} catch {
		return { props: { publication: null, footerPosts: [] }, revalidate: 60 };
	}
};
