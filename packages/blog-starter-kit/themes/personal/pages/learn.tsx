	if (name === 'home') return <svg {...common}><path d="m4 11 8-7 8 7v9a1 1 0 0 1-1 1h-5v-6h-4v6H5a1 1 0 0 1-1-1v-9Z" /></svg>;
	if (name === 'server') return <svg {...common}><rect x="4" y="4" width="16" height="5" rx="1.5" /><rect x="4" y="15" width="16" height="5" rx="1.5" /><path d="M8 6.5h.01M8 17.5h.01M7 9v6M17 9v6" /></svg>;
	if (name === 'layers') return <svg {...common}><path d="m12 3 8 4-8 4-8-4 8-4Z" /><path d="m4 12 8 4 8-4M4 17l8 4 8-4" /></svg>;
	if (name === 'network') return <svg {...common}><rect x="9" y="3" width="6" height="5" rx="1" /><rect x="3" y="16" width="6" height="5" rx="1" /><rect x="15" y="16" width="6" height="5" rx="1" /><path d="M12 8v4M6 16l6-4 6 4" /></svg>;
	if (name === 'cube') return <svg {...common}><path d="M12 3 4.5 7.2v9.6L12 21l7.5-4.2V7.2L12 3Z" /><path d="M4.7 7.4 12 11.5l7.3-4.1M12 21v-9.5" /></svg>;
	if (name === 'code') return <svg {...common}><path d="m8 9-4 3 4 3M16 9l4 3-4 3M14 5l-4 14" /></svg>;
	if (name === 'brain') return <svg {...common}><path d="M9 5a3 3 0 0 0-4 2.8A3.5 3.5 0 0 0 4 14a3 3 0 0 0 3 4h2V5ZM15 5a3 3 0 0 1 4 2.8A3.5 3.5 0 0 1 20 14a3 3 0 0 1-3 4h-2V5Z" /><path d="M12 5v14" /></svg>;
