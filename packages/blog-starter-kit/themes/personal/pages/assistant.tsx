const normalizeSuggestionKey = (value: string) =>
	value
		.toLowerCase()
		.replace(/\s+/g, ' ')
		.replace(/[?.!,:;"'`()[\]{}]+/g, '')
		.trim();

const parseSlashCommand = (value: string): { query: string; tab?: AssistantTab; personaBoost?: string } => {
	const trimmed = value.trim();
	if (!trimmed.startsWith('/')) return { query: trimmed };
	const [rawCommand, ...rest] = trimmed.split(/\s+/);
	const topic = rest.join(' ').trim();
	switch (rawCommand.toLowerCase()) {
		case '/roadmap':
			return { query: topic, tab: 'roadmap' };
		case '/visualize':
			return { query: topic, tab: 'concept-map', personaBoost: 'visual-learning' };
		case '/simulate':
			return {
				query: topic,
				tab: 'simulations',
				personaBoost: 'simulation-first',
			};
		case '/quiz':
			return { query: topic, tab: 'interview', personaBoost: 'quiz-mode' };
		case '/compare':
			return { query: topic, tab: 'answer', personaBoost: 'tradeoff-compare' };
		case '/deep-dive':
			return { query: topic, tab: 'answer', personaBoost: 'advanced-depth' };
		default:
			return { query: trimmed };
	}
};

