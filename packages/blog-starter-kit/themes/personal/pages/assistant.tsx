import { addPublicationJsonLd } from '@starter-kit/utils/seo/addPublicationJsonLd';
import { getAutogeneratedPublicationOG } from '@starter-kit/utils/social/og';
import { resizeImage } from '@starter-kit/utils/image';
import request from 'graphql-request';
import { GetStaticProps } from 'next';
import { motion, useReducedMotion } from 'framer-motion';
import Head from 'next/head';
import Link from 'next/link';
import { useRouter } from 'next/router';
import { useEffect, useMemo, useState } from 'react';
import { AppProvider } from '../components/contexts/appContext';
import { Container } from '../components/container';
import { Footer } from '../components/footer';
import { Layout } from '../components/layout';
import { PersonalHeader } from '../components/personal-theme-header';
import {
	MorePostsByPublicationDocument,
	MorePostsByPublicationQuery,
	MorePostsByPublicationQueryVariables,
	PostsByPublicationDocument,
	PostsByPublicationQuery,
	PostsByPublicationQueryVariables,
	PostFragment,
	PublicationByHostDocument,
	PublicationByHostQuery,
	PublicationByHostQueryVariables,
	PublicationFragment,
} from '../generated/graphql';
import { getFooterPosts } from '../lib/api/footerData';
import { getHoverLift, getRevealVariants, getTapScale } from '../components/motion-system';
import { PremiumSkeleton } from '../components/premium-skeleton';
import type { AssistantResponse } from './api/learning-assistant';

const GQL_ENDPOINT = process.env.NEXT_PUBLIC_HASHNODE_GQL_ENDPOINT;
const MEMORY_KEY = 'aa-learning-assistant-memory';

type AssistantPost = {
	id: string;
	title: string;
	slug: string;
	brief: string;
	readTimeInMinutes: number;
	views: number;
	tags?: Array<{ name: string; slug: string }> | null;
	coverImage?: { url?: string | null } | null;
};

type Turn = {
	id: number;
	query: string;
	response: AssistantResponse;
	visibleSections: number;
};

type Props = {
	publication: PublicationFragment;
	posts: AssistantPost[];
	footerPosts: PostFragment[];
};

const STREAM_SECTION_ORDER = [
	'overview',
	'prerequisites',
	'recommendedSequence',
	'relatedArchitectureTopics',
	'implementationArticles',
	'interviewQuestions',
	'conceptGraph',
	'adaptiveRecommendations',
] as const;

const sectionVisible = (turn: Turn, section: typeof STREAM_SECTION_ORDER[number]) => {
	const index = STREAM_SECTION_ORDER.indexOf(section);
	return turn.visibleSections > index;
};

const normalizeCoverImageUrl = (raw?: string | null) => {
	if (!raw) return null;
	const withProtocol = raw.startsWith('//') ? `https:${raw}` : raw;
	return resizeImage(withProtocol, { w: 960, h: 540, c: 'thumb' });
};

export default function LearningAssistantPage({ publication, posts, footerPosts }: Props) {
	const router = useRouter();
	const reduceMotion = useReducedMotion();
	const reveal = getRevealVariants(reduceMotion);
	const [query, setQuery] = useState('How do Kafka transactions work internally?');
	const [loading, setLoading] = useState(false);
	const [turns, setTurns] = useState<Turn[]>([]);
	const [error, setError] = useState<string | null>(null);

	useEffect(() => {
		try {
			const raw = sessionStorage.getItem(MEMORY_KEY);
			if (!raw) return;
			const saved = JSON.parse(raw) as Turn[];
			setTurns(saved);
		} catch {
			setTurns([]);
		}
	}, []);

	useEffect(() => {
		const q = typeof router.query.q === 'string' ? router.query.q : '';
		if (q?.trim()) {
			setQuery(q);
			runAssistant(q);
		}
		// run once when query param becomes available
		// eslint-disable-next-line react-hooks/exhaustive-deps
	}, [router.query.q]);

	useEffect(() => {
		try {
			sessionStorage.setItem(MEMORY_KEY, JSON.stringify(turns.slice(-8)));
		} catch {}
	}, [turns]);

	const currentTurn = turns[turns.length - 1] ?? null;
	const coverImageBySlug = useMemo(() => {
		const map = new Map<string, string>();
		for (const post of posts) {
			const image = normalizeCoverImageUrl(post.coverImage?.url);
			if (image) map.set(post.slug, image);
		}
		return map;
	}, [posts]);

	const resolveCoverImage = (slug: string) => coverImageBySlug.get(slug) ?? null;

	const history = useMemo(
		() =>
			turns.slice(-4).flatMap((turn) => [
				{ role: 'user' as const, content: turn.query },
				{ role: 'assistant' as const, content: turn.response.overview },
			]),
		[turns],
	);

	const runAssistant = async (nextQuery: string) => {
		const trimmed = nextQuery.trim();
		if (!trimmed) return;
		setLoading(true);
		setError(null);
		try {
			const res = await fetch('/api/learning-assistant', {
				method: 'POST',
				headers: { 'Content-Type': 'application/json' },
				body: JSON.stringify({
					query: trimmed,
					posts,
					history,
					persona: 'engineering-learning',
				}),
			});
			if (!res.ok) throw new Error(`Assistant error ${res.status}`);
			const payload = (await res.json()) as AssistantResponse;

			const turnId = Date.now();
			setTurns((prev) => [
				...prev,
				{
					id: turnId,
					query: trimmed,
					response: payload,
					visibleSections: 1,
				},
			]);

			let revealed = 1;
			const interval = window.setInterval(() => {
				revealed += 1;
				setTurns((prev) =>
					prev.map((turn) =>
						turn.id === turnId
							? { ...turn, visibleSections: Math.min(STREAM_SECTION_ORDER.length, revealed) }
							: turn,
					),
				);
				if (revealed >= STREAM_SECTION_ORDER.length) {
					window.clearInterval(interval);
				}
			}, 300);
		} catch (e) {
			setError(e instanceof Error ? e.message : 'Failed to run assistant');
		} finally {
			setLoading(false);
		}
	};

	return (
		<AppProvider publication={publication} footerPosts={footerPosts}>
			<Layout>
				<Head>
					<title>AI Learning Assistant - {publication.title}</title>
					<meta
						name="description"
						content="AI-native engineering learning navigator with semantic search, prerequisites, roadmap sequencing, adaptive recommendations, and interview prep."
					/>
					<meta property="og:title" content={`AI Learning Assistant - ${publication.title}`} />
					<meta
						property="og:description"
						content="Transform search into a structured engineering learning assistant."
					/>
					<meta
						property="og:image"
						content={publication.ogMetaData?.image || getAutogeneratedPublicationOG(publication)}
					/>
					<script
						type="application/ld+json"
						dangerouslySetInnerHTML={{ __html: JSON.stringify(addPublicationJsonLd(publication)) }}
					/>
				</Head>
				<Container className="mx-auto w-full">
					<PersonalHeader />
					<div className="max-w-7xl mx-auto w-full px-5 py-10">
						<div className="rounded-3xl border border-neutral-200/80 dark:border-neutral-800 bg-gradient-to-b from-white via-white to-blue-50/40 dark:from-neutral-900 dark:via-neutral-900 dark:to-blue-950/20 p-6 md:p-8 shadow-[0_8px_30px_rgba(0,0,0,0.05)] dark:shadow-none">
						<p className="inline-flex items-center rounded-full border border-blue-200 dark:border-blue-800 bg-blue-50 dark:bg-blue-950/40 px-2.5 py-1 text-[10px] font-mono uppercase tracking-widest text-blue-600 dark:text-blue-300">
							AI-native learning assistant
						</p>
						<motion.h1
							variants={reveal}
							initial="hidden"
							animate="show"
							className="mt-3 text-4xl md:text-5xl font-bold tracking-tight text-transparent bg-clip-text bg-gradient-to-r from-neutral-900 via-blue-700 to-indigo-700 dark:from-neutral-50 dark:via-blue-300 dark:to-indigo-300"
						>
							Intelligent Engineering Learning Navigator
						</motion.h1>
						<p className="mt-3 max-w-3xl text-neutral-600 dark:text-neutral-300 leading-relaxed">
							Semantic search + prerequisite reasoning + adaptive sequencing + interview prep in one guided flow.
						</p>

						<motion.div
							variants={reveal}
							initial="hidden"
							animate="show"
							className="mt-6 rounded-2xl border border-neutral-200/80 dark:border-neutral-800 bg-white/90 dark:bg-neutral-900/90 backdrop-blur p-4"
						>
							<div className="flex flex-col gap-3 md:flex-row">
								<input
									value={query}
									onChange={(e) => setQuery(e.target.value)}
									placeholder="Ask: How do Kafka transactions work internally?"
									className="w-full rounded-xl border border-neutral-200 dark:border-neutral-700 bg-neutral-50 dark:bg-neutral-950 px-4 py-3 text-sm text-neutral-800 dark:text-neutral-100 outline-none focus:border-blue-400 dark:focus:border-blue-500 focus:ring-2 focus:ring-blue-100 dark:focus:ring-blue-900/40"
								/>
								<motion.button
									onClick={() => runAssistant(query)}
									disabled={loading}
									whileTap={getTapScale(reduceMotion)}
									className="rounded-xl bg-gradient-to-r from-blue-600 to-indigo-600 px-4 py-3 text-sm font-semibold text-white hover:from-blue-700 hover:to-indigo-700 disabled:opacity-50 shadow-sm"
									aria-busy={loading}
								>
									{loading ? 'Thinking...' : 'Generate Learning Plan'}
								</motion.button>
							</div>
							<div className="mt-3 flex flex-wrap gap-2">
								{[
									'How do Kafka transactions work internally?',
									'Explain quorum reads and writes with trade-offs',
									'Design an LLM retrieval pipeline',
								].map((prompt) => (
									<motion.button
										key={prompt}
										onClick={() => {
											setQuery(prompt);
											runAssistant(prompt);
										}}
										whileHover={getHoverLift(reduceMotion)}
										whileTap={getTapScale(reduceMotion)}
										className="rounded-full border border-neutral-200 dark:border-neutral-700 px-3 py-1.5 text-xs text-neutral-600 dark:text-neutral-300 hover:border-blue-400 hover:text-blue-600 dark:hover:text-blue-400"
									>
										{prompt}
									</motion.button>
								))}
							</div>
						</motion.div>
						</div>

						{loading && (
							<div className="mt-4 grid grid-cols-1 gap-3 md:grid-cols-2">
								<PremiumSkeleton lines={5} />
								<PremiumSkeleton lines={4} />
							</div>
						)}

						{error && (
							<div className="mt-4 rounded-xl border border-rose-200 bg-rose-50 p-3 text-sm text-rose-700 dark:border-rose-800 dark:bg-rose-950/30 dark:text-rose-300">
								{error}
							</div>
						)}

						{currentTurn && (
							<div className="mt-6 grid grid-cols-1 gap-4 xl:grid-cols-[minmax(0,1fr)_320px]">
								<div className="space-y-4">
									<motion.div
										variants={reveal}
										initial="hidden"
										animate="show"
										className="rounded-xl border border-neutral-200 dark:border-neutral-800 bg-white dark:bg-neutral-900 p-4"
									>
										<p className="text-xs font-semibold uppercase tracking-wide text-neutral-500 dark:text-neutral-400">Query</p>
										<p className="mt-1 text-sm text-neutral-800 dark:text-neutral-100">{currentTurn.query}</p>
									</motion.div>

									{sectionVisible(currentTurn, 'overview') && (
										<motion.div variants={reveal} initial="hidden" animate="show" className="rounded-xl border border-neutral-200 dark:border-neutral-800 bg-white dark:bg-neutral-900 p-4">
											<p className="text-xs font-semibold uppercase tracking-wide text-neutral-500 dark:text-neutral-400">Overview</p>
											<p className="mt-2 text-sm leading-relaxed text-neutral-700 dark:text-neutral-300">{currentTurn.response.overview}</p>
										</motion.div>
									)}

									{sectionVisible(currentTurn, 'prerequisites') && (
										<div className="rounded-xl border border-neutral-200 dark:border-neutral-800 bg-white dark:bg-neutral-900 p-4">
											<p className="text-xs font-semibold uppercase tracking-wide text-neutral-500 dark:text-neutral-400">Prerequisite Concepts</p>
											<ul className="mt-2 list-disc pl-5 text-sm text-neutral-700 dark:text-neutral-300 space-y-1">
												{currentTurn.response.prerequisites.map((item) => <li key={item}>{item}</li>)}
											</ul>
										</div>
									)}

									{sectionVisible(currentTurn, 'recommendedSequence') && (
										<motion.div variants={reveal} initial="hidden" animate="show" className="rounded-xl border border-neutral-200 dark:border-neutral-800 bg-white dark:bg-neutral-900 p-4">
											<p className="text-xs font-semibold uppercase tracking-wide text-neutral-500 dark:text-neutral-400">Recommended Sequence</p>
											<div className="mt-2 space-y-2">
												{currentTurn.response.recommendedSequence.map((step, index) => (
													<motion.div key={step.slug} whileHover={getHoverLift(reduceMotion)}>
														<Link href={`/${step.slug}`} className="block rounded-lg border border-neutral-200 dark:border-neutral-700 p-3 hover:border-blue-300 dark:hover:border-blue-500">
															{resolveCoverImage(step.slug) ? (
																<img src={resolveCoverImage(step.slug)!} alt={step.title} className="mb-2 h-24 w-full rounded-md object-cover" />
															) : (
																<div className="mb-2 h-24 w-full rounded-md bg-gradient-to-br from-blue-100 via-indigo-100 to-teal-100 dark:from-blue-950/40 dark:via-indigo-950/30 dark:to-teal-950/30" />
															)}
															<p className="text-[11px] font-mono uppercase tracking-wide text-blue-600 dark:text-blue-400">Step {index + 1}</p>
															<p className="mt-1 text-sm font-semibold text-neutral-900 dark:text-neutral-50">{step.title}</p>
															<p className="mt-1 text-xs text-neutral-500 dark:text-neutral-400">{step.reason}</p>
														</Link>
													</motion.div>
												))}
											</div>
										</motion.div>
									)}

									{sectionVisible(currentTurn, 'relatedArchitectureTopics') && (
										<div className="rounded-xl border border-neutral-200 dark:border-neutral-800 bg-white dark:bg-neutral-900 p-4">
											<p className="text-xs font-semibold uppercase tracking-wide text-neutral-500 dark:text-neutral-400">Related Architecture Topics</p>
											<div className="mt-2 flex flex-wrap gap-2">
												{currentTurn.response.relatedArchitectureTopics.map((topic) => (
													<span key={topic} className="rounded-full bg-blue-100 dark:bg-blue-900/40 px-3 py-1 text-xs text-blue-700 dark:text-blue-300">{topic}</span>
												))}
											</div>
										</div>
									)}

									{sectionVisible(currentTurn, 'implementationArticles') && (
										<div className="rounded-xl border border-neutral-200 dark:border-neutral-800 bg-white dark:bg-neutral-900 p-4">
											<p className="text-xs font-semibold uppercase tracking-wide text-neutral-500 dark:text-neutral-400">Diagrams + Implementation Articles</p>
											<div className="mt-2 grid grid-cols-1 md:grid-cols-2 gap-2">
												{currentTurn.response.diagrams.map((item) => (
													<Link key={`d-${item.slug}`} href={`/${item.slug}`} className="rounded-lg border border-neutral-200 dark:border-neutral-700 p-3">
														{resolveCoverImage(item.slug) ? (
															<img src={resolveCoverImage(item.slug)!} alt={item.title} className="mb-2 h-20 w-full rounded-md object-cover" />
														) : (
															<div className="mb-2 h-20 w-full rounded-md bg-gradient-to-br from-blue-100 via-indigo-100 to-teal-100 dark:from-blue-950/40 dark:via-indigo-950/30 dark:to-teal-950/30" />
														)}
														<p className="text-[11px] font-semibold uppercase tracking-wide text-purple-600 dark:text-purple-300">Diagram</p>
														<p className="mt-1 text-sm text-neutral-800 dark:text-neutral-100">{item.title}</p>
													</Link>
												))}
												{currentTurn.response.implementationArticles.map((item) => (
													<Link key={`i-${item.slug}`} href={`/${item.slug}`} className="rounded-lg border border-neutral-200 dark:border-neutral-700 p-3">
														{resolveCoverImage(item.slug) ? (
															<img src={resolveCoverImage(item.slug)!} alt={item.title} className="mb-2 h-20 w-full rounded-md object-cover" />
														) : (
															<div className="mb-2 h-20 w-full rounded-md bg-gradient-to-br from-blue-100 via-indigo-100 to-teal-100 dark:from-blue-950/40 dark:via-indigo-950/30 dark:to-teal-950/30" />
														)}
														<p className="text-[11px] font-semibold uppercase tracking-wide text-emerald-600 dark:text-emerald-300">Implementation</p>
														<p className="mt-1 text-sm text-neutral-800 dark:text-neutral-100">{item.title}</p>
													</Link>
												))}
											</div>
										</div>
									)}

									{sectionVisible(currentTurn, 'interviewQuestions') && (
										<div className="rounded-xl border border-neutral-200 dark:border-neutral-800 bg-white dark:bg-neutral-900 p-4">
											<p className="text-xs font-semibold uppercase tracking-wide text-neutral-500 dark:text-neutral-400">Interview Prep Questions</p>
											<ul className="mt-2 list-disc pl-5 text-sm text-neutral-700 dark:text-neutral-300 space-y-1">
												{currentTurn.response.interviewQuestions.map((item) => <li key={item}>{item}</li>)}
											</ul>
										</div>
									)}
								</div>

								<div className="space-y-4">
									<motion.div variants={reveal} initial="hidden" animate="show" className="rounded-xl border border-neutral-200 dark:border-neutral-800 bg-white dark:bg-neutral-900 p-4">
										<p className="text-xs font-semibold uppercase tracking-wide text-neutral-500 dark:text-neutral-400">Difficulty Estimate</p>
										<p className="mt-1 text-lg font-bold text-neutral-900 dark:text-neutral-50">
											{currentTurn.response.difficultyEstimate.label} ({currentTurn.response.difficultyEstimate.score}/100)
										</p>
									</motion.div>

									{sectionVisible(currentTurn, 'conceptGraph') && (
										<div className="rounded-xl border border-neutral-200 dark:border-neutral-800 bg-white dark:bg-neutral-900 p-4">
											<p className="text-xs font-semibold uppercase tracking-wide text-neutral-500 dark:text-neutral-400">Concept Graph Traversal</p>
											<div className="mt-2 space-y-2">
												{currentTurn.response.conceptGraph.map((node) => (
													<div key={node.concept} className="rounded-lg bg-neutral-50 dark:bg-neutral-800/60 p-2 text-xs">
														<p className="font-semibold text-neutral-800 dark:text-neutral-100">{node.concept}</p>
														<p className="mt-1 text-neutral-500 dark:text-neutral-400">
															Depends on: {node.dependsOn.length ? node.dependsOn.join(', ') : 'Foundations'}
														</p>
													</div>
												))}
											</div>
										</div>
									)}

									{sectionVisible(currentTurn, 'adaptiveRecommendations') && (
										<motion.div variants={reveal} initial="hidden" animate="show" className="rounded-xl border border-neutral-200 dark:border-neutral-800 bg-white dark:bg-neutral-900 p-4">
											<p className="text-xs font-semibold uppercase tracking-wide text-neutral-500 dark:text-neutral-400">Adaptive Recommendations</p>
											<div className="mt-2 space-y-2">
												{currentTurn.response.adaptiveRecommendations.map((item) => (
													<motion.div key={item.slug} whileHover={getHoverLift(reduceMotion)}>
														<Link href={`/${item.slug}`} className="block rounded-lg border border-neutral-200 dark:border-neutral-700 p-2">
															{resolveCoverImage(item.slug) ? (
																<img src={resolveCoverImage(item.slug)!} alt={item.title} className="mb-2 h-20 w-full rounded-md object-cover" />
															) : (
																<div className="mb-2 h-20 w-full rounded-md bg-gradient-to-br from-blue-100 via-indigo-100 to-teal-100 dark:from-blue-950/40 dark:via-indigo-950/30 dark:to-teal-950/30" />
															)}
															<p className="text-sm font-semibold text-neutral-900 dark:text-neutral-50">{item.title}</p>
															<p className="mt-1 text-xs text-neutral-500 dark:text-neutral-400">{item.why}</p>
														</Link>
													</motion.div>
												))}
											</div>
										</motion.div>
									)}

									<motion.div variants={reveal} initial="hidden" animate="show" className="rounded-xl border border-neutral-200 dark:border-neutral-800 bg-white dark:bg-neutral-900 p-4">
										<p className="text-xs font-semibold uppercase tracking-wide text-neutral-500 dark:text-neutral-400">Prompt Orchestration + Retrieval</p>
										<p className="mt-2 text-xs text-neutral-500 dark:text-neutral-400">Retrieval query</p>
										<p className="mt-1 rounded-lg bg-neutral-50 dark:bg-neutral-800/60 p-2 text-xs text-neutral-700 dark:text-neutral-200">
											{currentTurn.response.promptPlan.retrievalQuery}
										</p>
										<ol className="mt-2 list-decimal pl-4 text-xs text-neutral-600 dark:text-neutral-300 space-y-1">
											{currentTurn.response.promptPlan.orchestrationSteps.map((step) => <li key={step}>{step}</li>)}
										</ol>
									</motion.div>
								</div>
							</div>
						)}
					</div>
					<Footer />
				</Container>
			</Layout>
		</AppProvider>
	);
}

export const getStaticProps: GetStaticProps<Props> = async () => {
	const publicationData = await request<PublicationByHostQuery, PublicationByHostQueryVariables>(
		GQL_ENDPOINT,
		PublicationByHostDocument,
		{
			host: process.env.NEXT_PUBLIC_HASHNODE_PUBLICATION_HOST,
		},
	);

	const publication = publicationData.publication;
	if (!publication) {
		return { notFound: true };
	}

	const first = await request<PostsByPublicationQuery, PostsByPublicationQueryVariables>(
		GQL_ENDPOINT,
		PostsByPublicationDocument,
		{ first: 20, host: process.env.NEXT_PUBLIC_HASHNODE_PUBLICATION_HOST },
	);

	const allPosts = (first.publication?.posts.edges ?? []).map((edge) => edge.node);
	let cursor = first.publication?.posts.pageInfo.endCursor;
	let hasNextPage = !!first.publication?.posts.pageInfo.hasNextPage;

	while (hasNextPage && cursor && allPosts.length < 260) {
		const next = await request<MorePostsByPublicationQuery, MorePostsByPublicationQueryVariables>(
			GQL_ENDPOINT,
			MorePostsByPublicationDocument,
			{ first: 20, host: process.env.NEXT_PUBLIC_HASHNODE_PUBLICATION_HOST, after: cursor },
		);
		if (!next.publication) break;
		allPosts.push(...next.publication.posts.edges.map((edge) => edge.node));
		cursor = next.publication.posts.pageInfo.endCursor;
		hasNextPage = !!next.publication.posts.pageInfo.hasNextPage;
	}

	const posts: AssistantPost[] = allPosts.slice(0, 250).map((post) => ({
		id: post.id,
		title: post.title,
		slug: post.slug,
		brief: post.brief,
		readTimeInMinutes: post.readTimeInMinutes,
		views: post.views ?? 0,
		tags: (post.tags ?? []).map((tag) => ({ name: tag.name, slug: tag.slug })),
		coverImage: post.coverImage ?? null,
	}));
	const footerPosts = await getFooterPosts();

	return {
		props: {
			publication,
			posts,
			footerPosts,
		},
		revalidate: 3600,
	};
};
