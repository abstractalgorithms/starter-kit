		setConversationMeta((prev) => ({ ...prev, [turnId]: { ...(prev[turnId] ?? {}), archived: true } }));

	const togglePinConversation = (turnId: number) =>
		setConversationMeta((prev) => ({
			...prev,
			[turnId]: { ...(prev[turnId] ?? {}), pinned: !prev[turnId]?.pinned },
		}));

