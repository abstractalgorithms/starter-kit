export const getStaticProps: GetStaticProps<Props> = async () => {
	try {
		const first = await request<PostsByPublicationQuery, PostsByPublicationQueryVariables>(
			GQL_ENDPOINT,
			PostsByPublicationDocument,
			{ first: 20, host: process.env.NEXT_PUBLIC_HASHNODE_PUBLICATION_HOST },
		);

		const publication = first.publication;
		if (!publication) return { notFound: true };

		const raw: PostFragment[] = [...(publication.posts.edges ?? []).map((edge) => edge.node)];
		let cursor = publication.posts.pageInfo.endCursor;
		let hasNextPage = !!publication.posts.pageInfo.hasNextPage;

		while (hasNextPage && cursor) {
			const next = await request<MorePostsByPublicationQuery, MorePostsByPublicationQueryVariables>(
				GQL_ENDPOINT,
				MorePostsByPublicationDocument,
				{ first: 20, host: process.env.NEXT_PUBLIC_HASHNODE_PUBLICATION_HOST, after: cursor },
			);
			if (!next.publication) break;
			raw.push(...next.publication.posts.edges.map((edge) => edge.node));
			cursor = next.publication.posts.pageInfo.endCursor;
			hasNextPage = !!next.publication.posts.pageInfo.hasNextPage;
		}

		const posts: LeanPost[] = raw.map((post) => ({
			id: post.id,
			title: post.title,
			slug: post.slug,
			brief: post.brief ?? '',
			readTimeInMinutes: post.readTimeInMinutes ?? 5,
			views: post.views ?? 0,
			publishedAt: post.publishedAt,
			tags: (post.tags ?? []).map((tag) => ({ id: tag.id, name: tag.name, slug: tag.slug })),
			series: post.series ? { name: post.series.name, slug: post.series.slug } : null,
		}));

		return {
			props: { publication, posts, footerPosts: raw.slice(0, 8) },
			revalidate: 3600,
		};
	} catch (error) {
		console.error('[interview-prep] getStaticProps error:', error);
		return { notFound: true };
	}
};
