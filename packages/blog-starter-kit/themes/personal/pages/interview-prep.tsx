const clamp = (value: number, min: number, max: number) => Math.max(min, Math.min(max, value));

const normalize = (value: string) => value.toLowerCase();

const postHaystack = (post: LeanPost) =>
	`${post.title} ${post.brief} ${post.series?.name ?? ''} ${post.tags.map((tag) => `${tag.name} ${tag.slug}`).join(' ')}`.toLowerCase();

const getMatchingPosts = (posts: LeanPost[], query: string[]) => {
	const matches = posts.filter((post) => {
		const haystack = postHaystack(post);
		return query.some((term) => haystack.includes(normalize(term)));
	});
	return matches.length > 0 ? matches : posts;
};

const getQuestionTitle = (post: LeanPost, categoryLabel: string) => {
	if (/design|architecture|system|distributed|database|kafka|raft|queue|cache/i.test(post.title)) {
		return post.title;
	}
	return `${categoryLabel}: ${post.title}`;
};

const getDifficulty = (minutes: number) => {
	if (minutes >= 13) return 'Advanced';
	if (minutes >= 7) return 'Intermediate';
	return 'Foundational';
};

const formatPercent = (value: number) => `${clamp(Math.round(value), 0, 100)}%`;

const loadPrepState = (): PrepState => {
	try {
		const raw = localStorage.getItem(PREP_STATE_KEY);
		return raw ? { ...DEFAULT_PREP_STATE, ...(JSON.parse(raw) as Partial<PrepState>) } : DEFAULT_PREP_STATE;
	} catch {
		return DEFAULT_PREP_STATE;
	}
};

const savePrepState = (state: PrepState) => {
	try {
		localStorage.setItem(PREP_STATE_KEY, JSON.stringify(state));
	} catch {}
};

