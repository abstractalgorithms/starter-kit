const readRecentlyViewed = (): RecentlyViewedItem[] => {
	if (typeof window === 'undefined') return [];
	try {
		const raw = localStorage.getItem(RECENTLY_VIEWED_KEY);
		if (!raw) return [];
		return JSON.parse(raw) as RecentlyViewedItem[];
	} catch {
		return [];
	}
};

const formatDuration = (minutes: number) => {
	if (minutes <= 0) return '';
	const hours = Math.floor(minutes / 60);
	const mins = minutes % 60;
	if (hours <= 0) return `${mins} min`;
	return mins > 0 ? `${hours}h ${mins}m` : `${hours}h`;
};

const formatViews = (views: number) => {
	if (views <= 0) return '';
	if (views >= 1000000) return `${(views / 1000000).toFixed(1).replace('.0', '')}M views`;
	if (views >= 1000) return `${(views / 1000).toFixed(1).replace('.0', '')}K views`;
	return `${views.toLocaleString()} views`;
};

const getSeriesImage = (s: Series, size: { w: number; h: number }) => {
	const source = s.coverImage || s.posts.find((post) => post.coverImage)?.coverImage;
	return source ? resizeImage(source, { ...size, c: 'thumb' }) : FALLBACK_POST_IMAGE;
};

const getSeriesOutcome = (s: Series) => {
	if (s.description) return s.description;
	const text = `${s.name} ${s.posts.map((post) => `${post.title} ${post.tags.map((tag) => tag.name).join(' ')}`).join(' ')}`;
	if (/kafka/i.test(text)) return 'Master Kafka architecture, use cases, and delivery trade-offs.';
	if (/distributed|consensus|replication/i.test(text)) return 'Build intuition for coordination, consistency, failure, and recovery.';
	if (/database|index|storage/i.test(text)) return 'Go deeper into how databases work and where their trade-offs appear.';
	if (/microservice|architecture/i.test(text)) return 'Learn practical service boundaries, deployment patterns, and reliability choices.';
	if (/system design|hld/i.test(text)) return 'Learn how to design scalable, reliable systems from requirements to trade-offs.';
	if (/ai|llm|vector|rag/i.test(text)) return 'Connect model behavior, retrieval systems, evaluation, and production guardrails.';
	return `A structured series for building practical understanding of ${s.name}.`;
};

const inferDomain = (name: string, description: string, posts: PostFragment[]) => {
	const haystack = `${name} ${description} ${posts.flatMap((post) => [post.title, post.brief, ...(post.tags ?? []).flatMap((tag) => [tag.name, tag.slug])]).join(' ')}`;
	return DOMAIN_PATTERNS.find((domain) => domain.pattern.test(haystack))?.label ?? 'Architecture';
};

const getLevel = (postCount: number, totalReadTime: number) => {
	if (postCount >= 18 || totalReadTime >= 480) return 'Intermediate';
	if (postCount >= 8 || totalReadTime >= 180) return 'Beginner to Intermediate';
	return 'Beginner';
};

