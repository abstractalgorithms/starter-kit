const formatViews = (views: number) => {
	if (!views) return 'New';
	if (views >= 1_000_000) return `${(views / 1_000_000).toFixed(1).replace('.0', '')}M views`;
	if (views >= 1_000) return `${(views / 1_000).toFixed(1).replace('.0', '')}K views`;
	return `${views} views`;
};

const formatDate = (value: string) => {
	const date = new Date(value);
	if (Number.isNaN(date.getTime())) return '';
	const days = Math.max(0, Math.floor((Date.now() - date.getTime()) / 86_400_000));
	if (days === 0) return 'Today';
	if (days === 1) return 'Yesterday';
	if (days < 30) return `${days} days ago`;
	if (days < 365) return `${Math.floor(days / 30)} months ago`;
	return `${Math.floor(days / 365)} years ago`;
};

const getTags = (video: YouTubeVideo) => {
	const text = `${video.title} ${video.description}`.toLowerCase();
	const tags = [
		['Data Structures', ['array', 'linked list', 'stack', 'queue', 'tree', 'graph']],
		['Algorithms', ['algorithm', 'complexity', 'sorting', 'search']],
		['System Design', ['system design', 'scalab', 'cache', 'database']],
		['Interview Prep', ['interview', 'question']],
	] as const;
	const matches = tags.filter(([, words]) => words.some((word) => text.includes(word))).map(([label]) => label);
	return [...matches, video.isShort ? 'Quick lesson' : 'Video'].slice(0, 3);
};

