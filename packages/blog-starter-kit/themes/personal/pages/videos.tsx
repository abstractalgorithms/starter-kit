export const getStaticProps: GetStaticProps<Props> = async () => {
	try {
		const channelId = process.env.YOUTUBE_CHANNEL_ID || DEFAULT_CHANNEL_ID;
		const [data, feedResult] = await Promise.all([
			request<PostsByPublicationQuery, PostsByPublicationQueryVariables>(GQL_ENDPOINT, PostsByPublicationDocument, {
				first: 8,
				host: process.env.NEXT_PUBLIC_HASHNODE_PUBLICATION_HOST,
			}),
			fetchYouTubeFeed(channelId).catch((error) => {
				console.error('[videos] YouTube feed error:', error);
				return { channelId, channelTitle: 'Abstract Algorithms', channelUrl: `https://www.youtube.com/channel/${channelId}`, videos: [] };
			}),
		]);
		if (!data.publication) return { notFound: true };
		return {
			props: {
				publication: data.publication,
				posts: data.publication.posts.edges.map((edge) => edge.node),
				feed: feedResult,
			},
			revalidate: Math.min(CONTENT_REVALIDATE_SECONDS, 3600),
		};
	} catch (error) {
		console.error('[videos] getStaticProps error:', error);
		return { notFound: true };
	}
};
