const readRecentlyViewed = (): RecentlyViewedItem[] => {
	if (typeof window === 'undefined') return [];
	try {
		const raw = localStorage.getItem(RECENTLY_VIEWED_KEY);
		if (!raw) return [];
		return JSON.parse(raw) as RecentlyViewedItem[];
	} catch {
		return [];
	}
};

const rememberPostView = (post: PostFragment) => {
	if (typeof window === 'undefined') return;
	try {
		const next = [
			{ slug: post.slug, title: post.title, seenAt: Date.now() },
			...readRecentlyViewed().filter((entry) => entry.slug !== post.slug),
		].slice(0, 20);
		localStorage.setItem(RECENTLY_VIEWED_KEY, JSON.stringify(next));
	} catch {}
};

const stripHtml = (value?: string | null) => value?.replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim() ?? '';

const formatDuration = (minutes: number) => {
	if (minutes <= 0) return '';
	const hours = Math.floor(minutes / 60);
	const mins = minutes % 60;
	if (hours <= 0) return `${mins} min`;
	return mins > 0 ? `${hours}h ${mins}m` : `${hours}h`;
};

const getSeriesOutcome = (series: SeriesInfo) => {
	const description = stripHtml(series.description);
	if (description) return description;
	const text = series.name.toLowerCase();
	if (/system design|hld|interview/.test(text)) {
		return 'A comprehensive series to help you design scalable, reliable, and fault-tolerant systems.';
	}
	if (/distributed|consensus|replication/.test(text)) {
		return 'A step-by-step path through coordination, consistency, failure handling, and recovery.';
	}
	if (/kafka|stream/.test(text)) {
		return 'A practical path through streaming architecture, partitions, brokers, and delivery guarantees.';
	}
	if (/ai|llm|rag|agent/.test(text)) {
		return 'A structured path through AI engineering, retrieval, evaluation, and production guardrails.';
	}
	return `A structured series for learning ${series.name} through published articles.`;
};

const getLevelLabel = (posts: PostFragment[]) => {
	const averageReadTime = posts.length ? posts.reduce((sum, post) => sum + post.readTimeInMinutes, 0) / posts.length : 0;
	if (posts.length >= 10 || averageReadTime >= 12) return 'Intermediate to Advanced';
	if (posts.length >= 4 || averageReadTime >= 7) return 'Beginner to Intermediate';
	return 'Beginner Friendly';
};

const getLatestUpdatedAt = (posts: PostFragment[]) =>
	posts
		.map((post) => post.updatedAt || post.publishedAt)
		.filter(Boolean)
		.sort()
		.at(-1);

const getPostImage = (post?: PostFragment | null) =>
	post?.coverImage?.url ? resizeImage(post.coverImage.url, { w: 360, h: 220, c: 'thumb' }) : FALLBACK_POST_IMAGE;

const chapterTitle = (title: string) =>
	title
		.replace(/^(chapter|part)\s+\d+\s*[:.-]\s*/i, '')
		.replace(/^\d+\s*[:.-]\s*/, '')
		.trim();

const getLearningOutcomes = (series: SeriesInfo, posts: PostFragment[]) => {
	const tagNames = [...new Set(posts.flatMap((post) => post.tags?.map((tag) => tag.name) ?? []))].slice(0, 3);
	return [
		`Understand ${series.name} through real published examples`,
		posts.length > 1 ? `Follow a sequence of ${posts.length} articles from fundamentals to deeper topics` : 'Start from the first published article in this series',
		tagNames.length ? `Connect related concepts: ${tagNames.join(', ')}` : 'Build practical engineering vocabulary',
		'Practice explaining trade-offs and implementation decisions',
	];
};

const getPrerequisites = (series: SeriesInfo) => {
	const lower = series.name.toLowerCase();
	if (/system design|distributed|kafka|architecture/.test(lower)) {
		return ['Basic backend engineering knowledge', 'Familiarity with APIs, databases, and caching', 'Comfort reading architecture trade-offs'];
	}
	if (/java|jvm|spring/.test(lower)) return ['Basic Java syntax', 'Object-oriented programming fundamentals', 'Comfort reading code examples'];
	if (/ai|llm|rag|vector/.test(lower)) return ['Basic API knowledge', 'Familiarity with data pipelines', 'Curiosity about model behavior'];
	return ['Basic software engineering knowledge', 'Comfort reading technical articles'];
};

