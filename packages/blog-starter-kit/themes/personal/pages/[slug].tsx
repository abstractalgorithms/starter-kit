type Params = {
	slug: string;
};

export const getStaticProps: GetStaticProps<Props, Params> = async ({ params }) => {
	if (!params) {
		throw new Error('No params');
	}

	const endpoint = process.env.NEXT_PUBLIC_HASHNODE_GQL_ENDPOINT;
	const host = process.env.NEXT_PUBLIC_HASHNODE_PUBLICATION_HOST;
	const slug = params.slug;

	let postData: SinglePostByPublicationQuery | undefined;
	try {
		postData = await request(endpoint, SinglePostByPublicationDocument, { host, slug });
	} catch (e) {
		console.warn('[getStaticProps] Hashnode API unavailable for slug:', slug, (e as Error).message);
		return { notFound: true, revalidate: 60 };
	}

	if (postData.publication?.post) {
		const footerPosts = await getFooterPosts();
		const currentPost = postData.publication.post;

		// ── Compute related posts from footerPosts by tag overlap + title similarity ──
		const currentTagSlugs = new Set((currentPost.tags ?? []).map((t) => t.slug));
		const currentKeywords = currentPost.title
			.toLowerCase()
			.replace(/[^\w\s]/g, ' ')
			.split(/\s+/)
			.filter((w) => w.length > 3);

		const scored = footerPosts
			.filter((p) => p.slug !== slug)
			.map((p) => {
				const tagScore = (p.tags ?? []).filter((t) => currentTagSlugs.has(t.slug)).length * 10;
				const titleWords = p.title.toLowerCase();
				const briefWords = (p.brief ?? '').toLowerCase();
				const kwScore = currentKeywords.reduce((s, w) => {
					return s + (titleWords.includes(w) ? 3 : 0) + (briefWords.includes(w) ? 1 : 0);
				}, 0);
				return { post: p, score: tagScore + kwScore };
			})
			.filter(({ score }) => score > 0)
			.sort((a, b) => b.score - a.score);

		// Require at least a tag match (>=10) or strong keyword overlap (>=6)
		const threshold = scored[0]?.score >= 10 ? 10 : 6;
		const morePosts = scored
			.filter(({ score }) => score >= threshold)
			.slice(0, 4)
			.map(({ post }) => post);

		return {
			props: {
				type: 'post',
				post: currentPost,
				publication: postData.publication,
				footerPosts,
				morePosts,
			},
			revalidate: 1,
		};
	}

	try {
		const pageData = await request(endpoint, PageByPublicationDocument, { host, slug });
		if (pageData.publication?.staticPage) {
			const footerPosts = await getFooterPosts();
			return {
				props: {
					type: 'page',
					page: pageData.publication.staticPage,
					publication: pageData.publication,
					footerPosts,
				},
				revalidate: 1,
			};
		}
	} catch (e) {
		console.warn('[getStaticProps] Page lookup failed for slug:', slug, (e as Error).message);
	}

	return {
		notFound: true,
		revalidate: 1,
	};
};

export async function getStaticPaths() {
	try {
		const data = await request(
			process.env.NEXT_PUBLIC_HASHNODE_GQL_ENDPOINT,
			SlugPostsByPublicationDocument,
			{
				first: 10,
				host: process.env.NEXT_PUBLIC_HASHNODE_PUBLICATION_HOST,
			},
		);

		const postSlugs = (data.publication?.posts.edges ?? []).map((edge) => edge.node.slug);

		return {
			paths: postSlugs.map((slug) => ({ params: { slug } })),
			fallback: 'blocking',
		};
	} catch (e) {
		console.warn('[getStaticPaths] Hashnode API unavailable, falling back to empty paths:', (e as Error).message);
		return { paths: [], fallback: 'blocking' };
	}
}
