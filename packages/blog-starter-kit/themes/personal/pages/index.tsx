import { getAutogeneratedPublicationOG } from '@starter-kit/utils/social/og';
import request from 'graphql-request';
import { GetStaticProps } from 'next';
import Head from 'next/head';
import { Container } from '../components/container';
import { AppProvider } from '../components/contexts/appContext';
import { Footer } from '../components/footer';
import { Layout } from '../components/layout';
import { NewsletterSection } from '../components/newsletter-section';
import { PersonalHeader } from '../components/personal-theme-header';
import { Hero, HeroStats } from '../components/hero';
import { StartHereSection, StartHereSeries } from '../components/start-here-section';
import { TopicCluster, buildTopicClusters } from '../components/topic-clusters';
import { PopularTopicsStrip } from '../components/popular-topics-strip';
import { PostChatbot } from '../components/post-chatbot';
import { AiTechTicker } from '../components/ai-tech-ticker';
import { TriviaOfDayCard } from '../components/trivia-of-day';
import { LearnToday, LearnPost } from '../components/learn-today';
import {
	MorePostsByPublicationDocument,
	MorePostsByPublicationQuery,
	MorePostsByPublicationQueryVariables,
	PostFragment,
	PostsByPublicationDocument,
	PostsByPublicationQuery,
	PostsByPublicationQueryVariables,
	PublicationFragment,
} from '../generated/graphql';

const GQL_ENDPOINT = process.env.NEXT_PUBLIC_HASHNODE_GQL_ENDPOINT;

type Props = {
	publication: PublicationFragment;
	initialPosts: PostFragment[];
	allPosts: LearnPost[];
	featuredSeries: StartHereSeries[];
	topicClusters: TopicCluster[];
	heroStats: HeroStats;
};

export default function Index({ publication, initialPosts, allPosts, featuredSeries, topicClusters, heroStats }: Props) {
	return (
		<AppProvider publication={publication} posts={initialPosts}>
			<Layout>
				<Head>
					<title>{publication.title}</title>
					<meta
						name="description"
						content={
							publication.descriptionSEO || publication.title || `${publication.author.name}'s Blog`
						}
					/>
					<meta property="twitter:card" content="summary_large_image" />
					<meta property="twitter:title" content={publication.displayTitle || publication.title || 'Hashnode Blog Starter Kit'} />
					<meta property="twitter:description" content={publication.descriptionSEO || publication.title || `${publication.author.name}'s Blog`} />
					<meta
						property="og:image"
						content={publication.ogMetaData.image || getAutogeneratedPublicationOG(publication)}
					/>
					<meta
						property="twitter:image"
						content={publication.ogMetaData.image || getAutogeneratedPublicationOG(publication)}
					/>
					<script
						type="application/ld+json"
						dangerouslySetInnerHTML={{
							__html: JSON.stringify(addPublicationJsonLd(publication)),
						}}
					/>
				</Head>
				<Container className="mx-auto w-full">
					<PersonalHeader />
					<div className="max-w-6xl mx-auto w-full px-5 flex flex-col gap-0 divide-y divide-neutral-200 dark:divide-neutral-800">

						{/* 1 ── Hero: strongest unique identifier, keep at top */}
						<Hero {...heroStats} />

						{/* 2 ── AI News ticker: fresh context right after the console hero */}
						<AiTechTicker />

						{/* 3 ── AI-Powered Discovery: search-first */}
						<LearnToday allPosts={allPosts} />

						{/* 4 ── Explore by Topic: chips for exploratory learners */}
						<PopularTopicsStrip clusters={topicClusters} allPosts={allPosts} />
							{/* 5 ── Curated Path: catch "Step 1" learners */}
							{featuredSeries.length > 0 && <StartHereSection series={featuredSeries} />}
						{/* 6 ── Daily trivia: fun engagement hook before the newsletter */}
						<TriviaOfDayCard />

						{/* 7 ── Newsletter */}
						<NewsletterSection />
					</div>
					<Footer />
					{/* Floating AI Chatbot */}
					<PostChatbot />
				</Container>
			</Layout>
		</AppProvider>
	);
}

export const getStaticProps: GetStaticProps<Props> = async () => {
	// ── 1. Fetch first page ──────────────────────────────────────────────────
	const data = await request<PostsByPublicationQuery, PostsByPublicationQueryVariables>(
		GQL_ENDPOINT,
		PostsByPublicationDocument,
		{
			first: 20,
			host: process.env.NEXT_PUBLIC_HASHNODE_PUBLICATION_HOST,
		},
	);

	const publication = data.publication;
	if (!publication) {
		return { notFound: true };
	}

	const initialPosts = (publication.posts.edges ?? []).map((edge) => edge.node);

	// ── 2. Paginate to collect all posts ─────────────────────────────────────
	const allPosts = [...initialPosts];
	let cursor = publication.posts.pageInfo.endCursor;
	let hasNextPage = !!publication.posts.pageInfo.hasNextPage;

	while (hasNextPage && cursor) {
		const next = await request<MorePostsByPublicationQuery, MorePostsByPublicationQueryVariables>(
			GQL_ENDPOINT,
			MorePostsByPublicationDocument,
			{ first: 20, host: process.env.NEXT_PUBLIC_HASHNODE_PUBLICATION_HOST, after: cursor },
		);
		if (!next.publication) break;
		allPosts.push(...next.publication.posts.edges.map((e) => e.node));
		cursor = next.publication.posts.pageInfo.endCursor;
		hasNextPage = !!next.publication.posts.pageInfo.hasNextPage;
	}

	// ── 3. Build topic clusters ───────────────────────────────────────────────
	const topicClusters: TopicCluster[] = buildTopicClusters(allPosts);

	// ── 4. Derive featured series ─────────────────────────────────────────────
	const seriesCountMap = new Map<string, { name: string; slug: string; count: number }>();
	for (const post of allPosts) {
		if (!post.series) continue;
		const { id, name, slug } = post.series;
		const prev = seriesCountMap.get(id);
		seriesCountMap.set(id, { name, slug, count: (prev?.count ?? 0) + 1 });
	}

	const topSeriesList = [...seriesCountMap.values()].sort((a, b) => b.count - a.count).slice(0, 3);

	const featuredSeries: StartHereSeries[] = topSeriesList.map((series) => {
		const seriesPosts = allPosts
			.filter((p) => p.series?.slug === series.slug)
			.sort((a, b) => new Date(a.publishedAt).getTime() - new Date(b.publishedAt).getTime());
		return { seriesName: series.name, seriesSlug: series.slug, posts: seriesPosts, totalPostCount: series.count };
	});

	// ── 5. Hero stats ─────────────────────────────────────────────────────────
	const topSeries = topSeriesList[0] ?? null;
	const heroStats: HeroStats = {
		totalPosts: allPosts.length,
		totalSeries: seriesCountMap.size,
		topSeries: topSeries ? { name: topSeries.name, postCount: topSeries.count } : null,
		topTags: topicClusters.slice(0, 6).map((c) => ({ label: c.label, slug: c.slug })),
	};

	return {
		props: {
			publication,
			initialPosts,
			allPosts: allPosts.map((p) => ({
				id: p.id,
				title: p.title,
				slug: p.slug,
				brief: p.brief,
				readTimeInMinutes: p.readTimeInMinutes,
				views: p.views,
				publishedAt: p.publishedAt,
				coverImage: p.coverImage ?? null,
				tags: p.tags ?? null,
				series: p.series ?? null,
			})),
			featuredSeries,
			topicClusters,
			heroStats,
		},
		revalidate: 1,
	};
};
